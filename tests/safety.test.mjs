// ============================================================================
// Файл: tests/safety.test.mjs
// Зачем нужен: проверка функции findContacts из js/safety.js — находит ли она
// телефоны, ссылки и @ники и не срабатывает ли на обычные сообщения.
// Как запустить: node tests/safety.test.mjs
// Как связан с остальными: импортирует js/safety.js (тот же код, что в чате).
// ============================================================================

// модуль проверок Node.js
import assert from 'node:assert/strict';
// проверяемая функция
import { findContacts } from '../js/safety.js';

// заголовок
console.log('\nПроверка поиска контактов (js/safety.js)\n');

// CASES — пары [текст, ожидаемый результат]
const CASES = [
  // телефон в международном формате
  ['Позвони мне +998 90 123-45-67', ['phone']],
  // телефон без пробелов
  ['мой номер 998901234567', ['phone']],
  // ссылка на Telegram
  ['пиши сюда t.me/amir_2010', ['link']],
  // обычная ссылка
  ['вот видео https://youtube.com/watch?v=1', ['link']],
  // сайт без http
  ['зайди на mysite.uz', ['link']],
  // ник
  ['мой инст @amir.super', ['nickname']],
  // ник в начале сообщения
  ['@lena_k напиши', ['nickname']],
  // обычное сообщение — ничего
  ['Давай в среду после уроков разберём задачу 15', []],
  // короткие числа (номер задачи, время) — не телефон
  ['Страница 134, задачи 5-7, в 15:30', []],
  // email-подобный текст без домена из списка — не ник (перед @ нет пробела)
  ['2+2=4, а 10@3 — ошибка', []],
// конец массива
];

// счётчики
let passed = 0;
// упавшие
let failed = 0;
// перебираем случаи; деструктуризация [text, expected]
for (const [text, expected] of CASES) {
  // try — проверка может не пройти
  try {
    // deepEqual сравнивает массивы по содержимому
    assert.deepEqual(findContacts(text), expected);
    // прошёл
    passed++;
    // печатаем
    console.log(`  ✔ «${text}» → [${expected.join(', ')}]`);
  // не прошёл
  } catch (error) {
    // счётчик
    failed++;
    // печатаем, что получили
    console.log(`  ✘ «${text}»: ожидали [${expected}], получили [${findContacts(text)}]`);
  // конец try/catch
  }
// конец цикла
}

// итог
console.log(`\nИтого: пройдено ${passed}, не пройдено ${failed}\n`);
// код ошибки для системы, если что-то упало
if (failed > 0) process.exitCode = 1;
