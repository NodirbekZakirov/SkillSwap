// ============================================================================
// Файл: tests/moderation.test.mjs
// Зачем нужен: проверка поиска грубых слов (js/moderation.js).
// Как запустить: node tests/moderation.test.mjs
// Как связан с остальными: импортирует js/moderation.js (тот же код, что на сайте).
// ============================================================================

// модуль проверок Node.js
import assert from 'node:assert/strict';
// проверяемые функции
import { findBadWords, highlightBadWords } from '../js/moderation.js';

// простое экранирование для теста (на сайте — escapeHtml из js/utils.js)
const escape = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

// счётчики
let passed = 0;
// упавшие
let failed = 0;

// ----------------------------------------------------------------------------
// test — запускает один тест и печатает результат.
// Принимает: name; fn. Возвращает: ничего.
// ----------------------------------------------------------------------------
// function
function test(name, fn) {
  // try — проверка может не пройти
  try {
    // запускаем
    fn();
    // прошёл
    passed++;
    // печатаем
    console.log(`  ✔ ${name}`);
  // не прошёл
  } catch (error) {
    // счётчик
    failed++;
    // причина
    console.log(`  ✘ ${name}\n    ${error.message}`);
  // конец try/catch
  }
// конец функции test
}

// заголовок
console.log('\nПроверка фильтра грубых слов (js/moderation.js)\n');

// находит грубые слова в любом регистре и с «ё»
test('Находит грубые слова в любом регистре', () => {
  // «Тупой» с большой буквы и «ИДИОТ» капсом
  assert.deepEqual(findBadWords('Тупой вопрос, ИДИОТ!'), ['тупой', 'идиот']);
// конец теста
});

// повторы не дублируются
test('Каждое слово — один раз', () => {
  // дважды «дурак»
  assert.deepEqual(findBadWords('дурак, ну дурак'), ['дурак']);
// конец теста
});

// не срабатывает на части других слов
test('Не срабатывает на похожие обычные слова', () => {
  // «тупик», «дураковаться» нет в списке, «лохматый» — не «лох»
  assert.deepEqual(findBadWords('Тупик в задаче, лохматый кот, урок'), []);
// конец теста
});

// обычный текст
test('Обычный ответ — без замечаний', () => {
  // нормальное объяснение
  assert.deepEqual(findBadWords('D = 25 − 24 = 1, значит x = 3 или x = 2'), []);
// конец теста
});

// подсветка
test('Подсветка: грубое слово в <mark>, HTML экранирован', () => {
  // в тексте есть и грубое слово, и попытка вставить тег
  const html = highlightBadWords('<b>тупой</b> вопрос', escape);
  // тег экранирован, слово выделено
  assert.equal(html, '&lt;b&gt;<mark class="bad-word">тупой</mark>&lt;/b&gt; вопрос');
// конец теста
});

// итог
console.log(`\nИтого: пройдено ${passed}, не пройдено ${failed}\n`);
// код ошибки, если что-то упало
if (failed > 0) process.exitCode = 1;
