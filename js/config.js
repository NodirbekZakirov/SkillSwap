// ----------------------------------------------------------------------------
// getSubject — находит предмет по его id.
// Принимает: subjectId — строку, например 'algebra'.
// Возвращает: объект предмета { id, name, icon } или «заглушку», если такого нет.
// ----------------------------------------------------------------------------
// export function — функция доступна другим модулям
export function getSubject(subjectId) {
  // find перебирает массив и возвращает первый элемент, для которого условие true; иначе undefined
  const subject = SUBJECTS.find((item) => item.id === subjectId);
  // ?? (оператор «нулевого слияния») — если слева null или undefined, берём значение справа
  return subject ?? { id: subjectId, name: subjectId, icon: '📘', withName: subjectId };
// конец функции getSubject
}
