// ============================================================================
// Файл: js/theme.js
// Зачем нужен: оживляет кнопку переключения темы (солнце / луна): при нажатии
// меняет тему и запоминает выбор в браузере.
// Как связан с остальными: это ES-модуль. Функцию initThemeToggle вызывают
// js/layout.js (шапка страниц внутри сайта) и js/pages/landing.js (главная).
// Начальную тему при загрузке ставит js/theme-init.js, ключ хранилища у них общий.
// ============================================================================

// const — постоянная; имя ключа в localStorage (то же самое, что в theme-init.js)
const THEME_KEY = 'skillswap-theme';

// ----------------------------------------------------------------------------
// getCurrentTheme — узнаёт, какая тема включена сейчас.
// Принимает: ничего.
// Возвращает: строку 'light' или 'dark'.
// ----------------------------------------------------------------------------
// function объявляет функцию; export делает её доступной для других файлов через import
export function getCurrentTheme() {
  // getAttribute читает атрибут data-theme у <html>; return возвращает результат из функции
  return document.documentElement.getAttribute('data-theme') === 'dark' ? 'dark' : 'light';
// конец функции getCurrentTheme
}

// ----------------------------------------------------------------------------
// setTheme — включает тему и запоминает выбор.
// Принимает: theme — строку 'light' или 'dark'.
// Возвращает: ничего.
// ----------------------------------------------------------------------------
// export function — объявляем и сразу экспортируем функцию
export function setTheme(theme) {
  // ставим атрибут data-theme, CSS сразу подхватывает новые цвета
  document.documentElement.setAttribute('data-theme', theme);
  // try — запись в localStorage может не сработать (запрещено хранилище), поэтому оборачиваем
  try {
    // setItem сохраняет значение theme под ключом THEME_KEY
    localStorage.setItem(THEME_KEY, theme);
  // catch — если запись не удалась, тема всё равно переключится, просто не запомнится
  } catch (error) {
    // console.warn выводит в консоль жёлтое предупреждение (не ошибку), чтобы разработчик знал причину
    console.warn('Не удалось сохранить тему:', error);
  // конец try/catch
  }
// конец функции setTheme
}

// ----------------------------------------------------------------------------
// initThemeToggle — подключает кнопку переключения темы.
// Принимает: button — HTML-элемент кнопки.
// Возвращает: ничего.
// ----------------------------------------------------------------------------
// export function — функцию вызывают другие модули
export function initThemeToggle(button) {
  // if (!button) — если кнопку не передали (null), ! означает «НЕ»
  if (!button) {
    // return без значения — просто выходим из функции, дальше ничего не делаем
    return;
  // конец if
  }
  // const updateIcon = () => { ... } — стрелочная функция (короткая запись функции), сохраняем её в переменную
  const updateIcon = () => {
    // узнаём текущую тему
    const theme = getCurrentTheme();
    // textContent — текст внутри кнопки: в тёмной теме показываем солнце (нажми, чтобы стало светло), в светлой — луну
    button.textContent = theme === 'dark' ? '☀️' : '🌙';
    // aria-label — подпись для программ чтения с экрана, потому что на кнопке только значок
    button.setAttribute('aria-label', theme === 'dark' ? 'Включить светлую тему' : 'Включить тёмную тему');
    // title — всплывающая подсказка при наведении мыши
    button.title = button.getAttribute('aria-label');
  // конец стрелочной функции updateIcon
  };
  // вызываем updateIcon сразу, чтобы значок соответствовал текущей теме
  updateIcon();
  // addEventListener('click', ...) — «подписываемся» на событие нажатия: функция выполнится при каждом клике
  button.addEventListener('click', () => {
    // выбираем противоположную тему
    const nextTheme = getCurrentTheme() === 'dark' ? 'light' : 'dark';
    // включаем и запоминаем её
    setTheme(nextTheme);
    // обновляем значок на кнопке
    updateIcon();
  // конец обработчика клика: ) закрывает вызов addEventListener
  });
// конец функции initThemeToggle
}
