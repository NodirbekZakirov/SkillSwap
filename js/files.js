// ============================================================================
// Файл: js/files.js
// Зачем нужен: чистые функции для файлов-материалов:
//   • validateFile — проверка типа (только картинки и PDF) и размера (до 5 МБ);
//   • formatFileSize — «1,2 МБ» вместо «1258291»;
//   • buildStoragePath — безопасный путь файла в хранилище.
// Функции не трогают базу и страницу, поэтому их проверяет тест
// tests/files.test.mjs.
// Как связан с остальными: правила берутся из js/config.js; функции
// используют js/pages/materials.js и js/qa.js (фото к вопросам и ответам).
// Те же ограничения стоят и на сервере (корзины materials и qa-images
// в sql/schema.sql), так что обойти их нельзя.
// ============================================================================

// правила: максимальный размер и разрешённые типы
import { MAX_FILE_SIZE, ALLOWED_FILE_TYPES } from './config.js';

// ----------------------------------------------------------------------------
// formatFileSize — размер файла по-человечески.
// Принимает: bytes — размер в байтах. Возвращает: строку, например «1,2 МБ».
// ----------------------------------------------------------------------------
// export function
export function formatFileSize(bytes) {
  // меньше 1 КБ — в байтах
  if (bytes < 1024) return `${bytes} Б`;
  // меньше 1 МБ — в килобайтах, без дробной части
  if (bytes < 1024 * 1024) return `${Math.round(bytes / 1024)} КБ`;
  // toFixed(1) — одна цифра после точки; replace меняет точку на запятую, как принято в русском языке
  return `${(bytes / (1024 * 1024)).toFixed(1).replace('.', ',')} МБ`;
// конец функции formatFileSize
}

// ----------------------------------------------------------------------------
// validateFile — проверяет выбранный файл.
// Принимает: file — объект File из <input type="file"> (нужны поля type и size)
//   или null, если ничего не выбрано; options.imagesOnly — true, если PDF
//   нельзя (фото к вопросам и ответам).
// Возвращает: текст ошибки на русском или '' (ошибок нет).
// ----------------------------------------------------------------------------
// { imagesOnly = false } = {} — необязательный параметр-объект
export function validateFile(file, { imagesOnly = false } = {}) {
  // файл не выбран
  if (!file) return 'Выбери файл';
  // пустой файл (0 байт)
  if (file.size === 0) return 'Файл пустой';
  // in — есть ли такой ключ в объекте; тип не из списка разрешённых
  if (!(file.type in ALLOWED_FILE_TYPES)) {
    // список разрешённых типов для подсказки: «JPG, PNG, WebP, GIF, PDF»
    const allowed = Object.values(ALLOWED_FILE_TYPES).map((t) => t.label).join(', ');
    // текст ошибки
    return `Такой файл загрузить нельзя. Можно только: ${allowed}`;
  // конец if
  }
  // только картинки, а выбран PDF
  if (imagesOnly && !isImage(file.type)) return 'Здесь можно прикрепить только фото: JPG, PNG, WebP или GIF';
  // слишком большой
  if (file.size > MAX_FILE_SIZE) return `Файл слишком большой (${formatFileSize(file.size)}). Максимум — ${formatFileSize(MAX_FILE_SIZE)}`;
  // всё хорошо
  return '';
// конец функции validateFile
}

// ----------------------------------------------------------------------------
// buildStoragePath — путь файла в хранилище: «12/1727000000000-a1b2c3.pdf».
// Первая папка — номер партнёрства (материалы) или номер школы (фото вопросов):
// по ней правила Storage проверяют, есть ли у пользователя доступ. Настоящее имя файла (может быть на русском)
// хранится отдельно в таблице materials, а в путь идут только цифры и
// латиница — так хранилище точно примет файл.
// Принимает: partnershipId — номер первой папки (партнёрства или школы); mimeType — тип файла; now — время
//   (передаётся параметром, чтобы функцию было легко проверить тестом);
//   random — случайная строка.
// Возвращает: строку пути.
// ----------------------------------------------------------------------------
// значения по умолчанию: текущее время и случайная строка из 6 символов
export function buildStoragePath(partnershipId, mimeType, now = Date.now(), random = Math.random().toString(36).slice(2, 8)) {
  // расширение по типу файла (jpg, pdf...)
  const ext = ALLOWED_FILE_TYPES[mimeType]?.ext ?? 'bin';
  // склеиваем части пути
  return `${partnershipId}/${now}-${random}.${ext}`;
// конец функции buildStoragePath
}

// ----------------------------------------------------------------------------
// isImage — картинка ли это (для превью).
// Принимает: mimeType. Возвращает: boolean.
// ----------------------------------------------------------------------------
// export function
export function isImage(mimeType) {
  // startsWith — начинается ли строка с «image/»
  return mimeType.startsWith('image/');
// конец функции isImage
}
