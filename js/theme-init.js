// ============================================================================
// Файл: js/theme-init.js
// Зачем нужен: включает светлую или тёмную тему ДО того, как браузер нарисует
// страницу. Если сделать это позже, при каждой загрузке будет мелькать белый
// экран («вспышка» светлой темы).
// Как связан с остальными: подключается обычным <script> (не модулем) в <head>
// КАЖДОЙ страницы. Ставит атрибут data-theme на <html>, а css/variables.css
// по этому атрибуту выбирает цвета. Кнопку переключения темы обслуживает
// js/theme.js, он сохраняет выбор под тем же ключом THEME_KEY.
// ============================================================================

// { } — просто блок кода; const внутри блока видны только в нём и не мешают другим скриптам
{
  // const создаёт переменную, которую нельзя перезаписать; здесь это имя ключа, под которым выбор темы лежит в хранилище браузера
  const THEME_KEY = 'skillswap-theme';
  // let создаёт переменную, которую МОЖНО перезаписать; null означает «пока ничего нет»
  let savedTheme = null;
  // try { } — пробуем выполнить код; если внутри случится ошибка, программа не упадёт, а перейдёт в catch
  try {
    // localStorage — хранилище браузера, которое не очищается при закрытии вкладки; getItem читает значение по ключу
    savedTheme = localStorage.getItem(THEME_KEY);
  // catch (error) — сюда попадаем, если localStorage запрещён (например, в режиме «инкогнито» некоторых браузеров)
  } catch (error) {
    // ничего не делаем: просто остаётся тема по умолчанию; savedTheme уже равна null
    savedTheme = null;
  // конец блока try/catch
  }
  // window.matchMedia проверяет медиазапрос; '(prefers-color-scheme: dark)' — включена ли тёмная тема в системе; .matches — true или false
  const systemPrefersDark = window.matchMedia('(prefers-color-scheme: dark)').matches;
  // тернарный оператор «условие ? A : B»: если системная тема тёмная — 'dark', иначе — 'light'
  const systemTheme = systemPrefersDark ? 'dark' : 'light';
  // || (ИЛИ) берёт первое «непустое» значение: если тема сохранена — она, иначе системная
  const themeToApply = savedTheme || systemTheme;
  // document.documentElement — это тег <html>; setAttribute ставит ему атрибут data-theme="light" или "dark"
  document.documentElement.setAttribute('data-theme', themeToApply);
// конец блока
}
