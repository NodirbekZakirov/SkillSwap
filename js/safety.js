// ============================================================================
// Файл: js/safety.js
// Зачем нужен: безопасность детей в чате. Функция findContacts ищет в тексте
// то, чем обычно делятся для общения «вне сайта»: номер телефона, ссылку,
// @ник (Telegram, Instagram). Если что-то найдено, чат показывает
// предупреждение «Не делись личными контактами, договаривайтесь здесь».
// Здесь только чистые функции (без работы с базой и страницей), поэтому их
// легко проверить тестом: tests/safety.test.mjs.
// Как связан с остальными: используется в js/pages/chat.js.
// ============================================================================

// CONTACT_WARNING — текст предупреждения (одно место, чтобы легко поменять)
export const CONTACT_WARNING = 'Не делись личными контактами, договаривайтесь здесь';

// CONTACT_PATTERNS — регулярные выражения (шаблоны поиска) для каждого вида контакта
const CONTACT_PATTERNS = {
  // телефон: необязательный «+», затем цифра, потом 7 и больше цифр, пробелов, дефисов или скобок, в конце цифра; например +998 90 123-45-67
  phone: /\+?\d[\d\s\-()]{7,}\d/,
  // ссылка: http:// или https://, www., t.me/, или «слово.домен» с популярными окончаниями; \b — граница слова; флаг i — без учёта регистра
  link: /(https?:\/\/|www\.|t\.me\/|\b[a-z0-9-]+\.(com|ru|uz|net|org|me|io|ly|gg|app|site)\b)/i,
  // @ник: знак @ после начала строки или пробела и минимум 3 буквы, цифры, «_» или «.»; (^|\s) — начало строки или пробельный символ
  nickname: /(^|\s)@[a-z0-9_.]{3,}/i,
// конец объекта
};

// CONTACT_NAMES — названия видов контактов по-русски (для подсказки)
const CONTACT_NAMES = {
  // телефон
  phone: 'номер телефона',
  // ссылка
  link: 'ссылка',
  // ник
  nickname: '@ник',
// конец объекта
};

// ----------------------------------------------------------------------------
// findContacts — ищет в тексте личные контакты.
// Принимает: text — текст сообщения.
// Возвращает: массив видов найденных контактов, например ['phone', 'link'];
//   пустой массив — контактов нет.
// ----------------------------------------------------------------------------
// export function
export function findContacts(text) {
  // String(text ?? '') — защита от null; Object.entries — пары [вид, шаблон]
  return Object.entries(CONTACT_PATTERNS)
    // test проверяет, есть ли совпадение с шаблоном
    .filter(([, pattern]) => pattern.test(String(text ?? '')))
    // оставляем только название вида
    .map(([kind]) => kind);
// конец функции findContacts
}

// ----------------------------------------------------------------------------
// describeContacts — человеческое описание найденного: «номер телефона и ссылка».
// Принимает: kinds — массив из findContacts. Возвращает: строку.
// ----------------------------------------------------------------------------
// export function
export function describeContacts(kinds) {
  // переводим каждый вид в слова и соединяем через « и »
  return kinds.map((kind) => CONTACT_NAMES[kind]).join(' и ');
// конец функции describeContacts
}
