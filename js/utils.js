// Файл: js/utils.js
// Зачем нужен: маленькие полезные функции, которые нужны на многих страницах:
// защита от вставки HTML-кода (экранирование), всплывающие сообщения (тосты),
// защита кнопки от двойного нажатия, блоки «загрузка / пусто / ошибка».
// Как связан с остальными: другие модули импортируют отсюда нужные функции,
// например: import { escapeHtml, showToast } from '../utils.js'.
// Внешний вид тостов и состояний описан в css/components.css.
