// ----------------------------------------------------------------------------
// escapeHtml — делает текст безопасным для вставки в HTML.
// Если ученик напишет в чате <script>...</script>, без экранирования браузер
// выполнил бы этот код. Мы заменяем опасные символы на «HTML-сущности»,
// и браузер просто покажет их как обычный текст.
// Принимает: value — любой текст (или число, или null).
// Возвращает: безопасную строку.
// ----------------------------------------------------------------------------
// export function — функцию можно импортировать в других файлах
export function escapeHtml(value) {
  // String(value ?? '') — превращаем значение в строку; если оно null/undefined, берём пустую строку
  return String(value ?? '')
    // replace(/&/g, '&amp;') — /&/g это регулярное выражение «символ &», флаг g значит «заменить ВСЕ», а не только первый
    .replace(/&/g, '&amp;')
    // < открывает HTML-тег, заменяем на &lt; (less than — «меньше»)
    .replace(/</g, '&lt;')
    // > закрывает HTML-тег, заменяем на &gt; (greater than — «больше»)
    .replace(/>/g, '&gt;')
    // двойная кавычка может «закрыть» значение атрибута, заменяем на &quot;
    .replace(/"/g, '&quot;')
    // одинарная кавычка — то же самое, &#39; это её код
    .replace(/'/g, '&#39;');
// конец функции escapeHtml
}

// ----------------------------------------------------------------------------
// getToastContainer — находит (или создаёт) место в углу экрана для тостов.
// Принимает: ничего.
// Возвращает: HTML-элемент контейнера.
// ----------------------------------------------------------------------------
// function без export — эта функция нужна только внутри этого файла
function getToastContainer() {
  // querySelector ищет на странице ПЕРВЫЙ элемент по CSS-селектору; точка означает класс
  let container = document.querySelector('.toast-container');
  // если контейнера ещё нет
  if (!container) {
    // createElement создаёт новый HTML-элемент div (пока он нигде не показан)
    container = document.createElement('div');
    // className задаёт CSS-класс элемента
    container.className = 'toast-container';
    // role="status" + aria-live="polite" — программа чтения с экрана прочитает новые сообщения вслух
    container.setAttribute('role', 'status');
    // aria-live="polite" — «вежливо»: дождётся паузы и только потом прочитает
    container.setAttribute('aria-live', 'polite');
    // append добавляет элемент в конец body — теперь он появился на странице
    document.body.append(container);
  // конец if
  }
  // возвращаем найденный или созданный контейнер
  return container;
// конец функции getToastContainer
}

// ----------------------------------------------------------------------------
// showToast — показывает всплывающее сообщение в углу экрана на 4 секунды.
// Принимает: message — текст сообщения; type — 'info', 'success' или 'error'.
// Возвращает: ничего.
// ----------------------------------------------------------------------------
// type = 'info' — значение по умолчанию: если второй аргумент не передали, будет 'info'
export function showToast(message, type = 'info') {
  // создаём элемент сообщения
  const toast = document.createElement('div');
  // `toast toast-${type}` — шаблонная строка в обратных кавычках: ${...} подставляет значение переменной
  toast.className = `toast toast-${type}`;
  // textContent вставляет ТЕКСТ (не HTML), поэтому здесь экранирование не нужно: теги не сработают
  toast.textContent = message;
  // добавляем сообщение в контейнер — оно появляется на экране
  getToastContainer().append(toast);
  // по клику сообщение сразу исчезает; remove() удаляет элемент со страницы
  toast.addEventListener('click', () => toast.remove());
  // setTimeout(функция, 4000) — выполнить функцию один раз через 4000 миллисекунд (4 секунды)
  setTimeout(() => toast.remove(), 4000);
// конец функции showToast
}

// ----------------------------------------------------------------------------
// setButtonLoading — включает или выключает у кнопки режим «идёт отправка».
// Пока идёт запрос, кнопка отключена: второе нажатие ничего не сделает.
// Так мы защищаемся от двойной отправки формы.
// Принимает: button — кнопку; isLoading — true (включить) или false (выключить).
// Возвращает: ничего.
// ----------------------------------------------------------------------------
// export function — используется во всех формах
export function setButtonLoading(button, isLoading) {
  // если кнопку не передали, выходим
  if (!button) return;
  // disabled = true отключает кнопку: на неё нельзя нажать, и форма не отправится второй раз
  button.disabled = isLoading;
  // classList.toggle(класс, условие) добавляет класс, если условие true, и убирает, если false; класс is-loading рисует крутящийся кружок
  button.classList.toggle('is-loading', isLoading);
  // aria-busy сообщает программам чтения с экрана, что идёт загрузка
  button.setAttribute('aria-busy', String(isLoading));
// конец функции setButtonLoading
}

// ----------------------------------------------------------------------------
// renderState — показывает в контейнере одно из состояний экрана.
// Принимает: container — HTML-элемент, куда рисовать;
//            type — 'loading' (загрузка), 'empty' (пусто) или 'error' (ошибка);
//            title — заголовок; text — пояснение (необязательно);
//            action — кнопка-ссылка { href, label } (необязательно), например
//            { href: '/pages/profile.html', label: 'Заполнить профиль' }.
// Возвращает: ничего.
// ----------------------------------------------------------------------------
// text = '' и action = null — по умолчанию пояснения и кнопки нет
export function renderState(container, type, title, text = '', action = null) {
  // если контейнера нет, рисовать некуда
  if (!container) return;
  // объект-словарь: для каждого типа своя иконка; для загрузки вместо иконки крутящийся кружок
  const icons = { empty: '🌱', error: '⚠️', success: '✅' };
  // для загрузки рисуем спиннер, для остальных — эмодзи; escapeHtml не нужен, потому что иконки мы задали сами
  const iconHtml = type === 'loading' ? '<div class="spinner" aria-hidden="true"></div>' : `<div class="state-icon" aria-hidden="true">${icons[type] ?? '💡'}</div>`;
  // role="alert" — ошибку программа чтения с экрана прочитает сразу, role="status" — остальное спокойно
  const role = type === 'error' ? 'alert' : 'status';
  // innerHTML заменяет содержимое контейнера на HTML-код; собираем код из массива строк, join('') склеивает их без разделителя
  container.innerHTML = [
    // открываем блок состояния
    `<div class="state" role="${role}">`,
    // иконка или спиннер
    iconHtml,
    // заголовок; escapeHtml защищает от вставки HTML-кода
    `<p class="state-title">${escapeHtml(title)}</p>`,
    // пояснение показываем, только если оно передано; иначе пустая строка
    text ? `<p>${escapeHtml(text)}</p>` : '',
    // кнопка-ссылка, если передана; адрес и подпись тоже экранируем
    action ? `<a class="btn btn-primary" href="${escapeHtml(action.href)}">${escapeHtml(action.label)}</a>` : '',
    // закрываем блок
    '</div>',
  // ].join('') — закрываем массив и склеиваем все строки в одну
  ].join('');
// конец функции renderState
}

// ----------------------------------------------------------------------------
// logError — записывает подробности ошибки в консоль для разработчика.
// Ошибку мы уже показали пользователю понятным сообщением, поэтому в консоль
// пишем ЖЁЛТОЕ предупреждение (console.warn), а не красную ошибку:
// по заданию в консоли браузера не должно быть ошибок.
// Принимает: error — объект ошибки. Возвращает: ничего.
// ----------------------------------------------------------------------------
// export function — используется во всех блоках catch
export function logError(error) {
  // console.warn выводит предупреждение; первым аргументом — подпись, вторым — сама ошибка
  console.warn('SkillSwap:', error?.message ?? error);
// конец функции logError
}

// ----------------------------------------------------------------------------
// getErrorMessage — превращает техническую ошибку в понятный текст на русском.
// Принимает: error — объект ошибки (от Supabase или от браузера).
// Возвращает: строку для показа пользователю.
// ----------------------------------------------------------------------------
// export function — используется во всех блоках catch
export function getErrorMessage(error) {
  // ?. — «безопасный доступ»: если error равен null, не будет ошибки, получим undefined; toLowerCase делает все буквы маленькими
  const text = String(error?.message ?? '').toLowerCase();
  // код P0001 — ошибка, которую мы сами «бросили» в SQL командой raise exception; её текст уже написан по-русски для ученика
  if (error?.code === 'P0001' && error.message) {
    // возвращаем этот текст как есть
    return error.message;
  // конец if
  }
  // в базе нет нужной таблицы или функции: PGRST205 / 42P01 — таблицы, PGRST202 / 42883 — функции (SQL-скрипт ещё не выполнен)
  if (['PGRST205', 'PGRST202', '42P01', '42883'].includes(error?.code) || text.includes('schema cache')) {
    // объясняем причину и что сделать
    return 'Эта часть сайта ещё не подключена к базе данных. Администратору: выполни в Supabase (SQL Editor) файл sql/schema.sql.';
  // конец if
  }
  // если нет интернета, fetch падает с текстом «failed to fetch»
  if (text.includes('failed to fetch') || text.includes('networkerror')) {
    // понятный текст для ученика
    return 'Нет связи с сервером. Проверь интернет и попробуй ещё раз.';
  // конец if
  }
  // нарушен внешний ключ: например, удаляют школу, в которой есть пользователи (on delete restrict в schema.sql)
  if (text.includes('foreign key')) {
    // понятный текст
    return 'Нельзя удалить: к этой записи привязаны пользователи или другие данные.';
  // конец if
  }
  // нарушена уникальность: например, школа с таким названием уже есть
  if (text.includes('duplicate key') || text.includes('unique')) {
    // понятный текст
    return 'Такая запись уже есть. Проверь название.';
  // конец if
  }
  // Storage отклонил файл из-за размера (ограничение корзины 5 МБ)
  if (text.includes('maximum allowed size') || text.includes('payload too large') || text.includes('too large')) {
    // понятный текст
    return 'Файл слишком большой. Максимум — 5 МБ.';
  // конец if
  }
  // Storage отклонил тип файла
  if (text.includes('mime type') || text.includes('not supported')) {
    // понятный текст
    return 'Такой тип файла загрузить нельзя. Можно картинки и PDF.';
  // конец if
  }
  // неправильный ключ в js/config.js (опечатка или секретный ключ вместо публичного)
  if (text.includes('api key')) {
    // подсказка, где исправить
    return 'Сайт неправильно подключён к базе: проверь ключ в js/config.js (нужен Publishable key).';
  // конец if
  }
  // Supabase пишет «invalid login credentials», если email или пароль неверные
  if (text.includes('invalid login credentials')) {
    // сообщение про неверный вход
    return 'Неверный email или пароль.';
  // конец if
  }
  // пользователь с таким email уже есть
  if (text.includes('already registered') || text.includes('already been registered')) {
    // сообщение про занятый email
    return 'Этот email уже зарегистрирован. Попробуй войти.';
  // конец if
  }
  // email ещё не подтверждён по ссылке из письма
  if (text.includes('email not confirmed')) {
    // сообщение про подтверждение
    return 'Подтверди email: открой ссылку из письма, которое мы отправили.';
  // конец if
  }
  // слишком много попыток подряд (Supabase ограничивает частоту писем и входов)
  if (text.includes('rate limit') || text.includes('too many requests') || text.includes('security purposes')) {
    // просим подождать
    return 'Слишком много попыток. Подожди пару минут и попробуй снова.';
  // конец if
  }
  // пароль короче, чем требует Supabase
  if (text.includes('password should be')) {
    // сообщение про пароль
    return 'Пароль слишком простой или короткий. Придумай пароль подлиннее.';
  // конец if
  }
  // новый пароль совпадает со старым
  if (text.includes('different from the old password')) {
    // сообщение
    return 'Новый пароль должен отличаться от старого.';
  // конец if
  }
  // ссылка из письма устарела или уже использована; скобки показывают порядок: «expired» ИЛИ (есть «invalid» И «token»)
  if (text.includes('expired') || (text.includes('invalid') && text.includes('token'))) {
    // сообщение
    return 'Ссылка устарела. Запроси новое письмо.';
  // конец if
  }
  // RLS не пустила к данным (в тексте ошибки есть «row-level security» или «permission denied»)
  if (text.includes('row-level security') || text.includes('permission denied')) {
    // сообщение про права
    return 'Недостаточно прав для этого действия.';
  // конец if
  }
  // для всех остальных случаев общий текст
  return 'Что-то пошло не так. Попробуй ещё раз чуть позже.';
// конец функции getErrorMessage
}

// ----------------------------------------------------------------------------
// formatDateTime — дата и время по-русски: «25 сент., 15:30».
// Intl.DateTimeFormat — встроенный в браузер «переводчик» дат на нужный язык.
// Принимает: value — дата (строка из базы или объект Date).
// Возвращает: строку.
// ----------------------------------------------------------------------------
// export function
export function formatDateTime(value) {
  // new Date(value) — превращаем строку из базы в объект даты
  return new Intl.DateTimeFormat('ru-RU', { day: 'numeric', month: 'short', hour: '2-digit', minute: '2-digit' }).format(new Date(value));
// конец функции formatDateTime
}

// ----------------------------------------------------------------------------
// formatTime — только время: «15:30».
// Принимает: value — дата. Возвращает: строку.
// ----------------------------------------------------------------------------
// export function
export function formatTime(value) {
  // hour и minute — часы и минуты двумя цифрами
  return new Intl.DateTimeFormat('ru-RU', { hour: '2-digit', minute: '2-digit' }).format(new Date(value));
// конец функции formatTime
}

// ----------------------------------------------------------------------------
// formatDay — день для разделителя в чате: «Сегодня», «Вчера» или «25 сентября».
// Принимает: value — дата. Возвращает: строку.
// ----------------------------------------------------------------------------
// export function
export function formatDay(value) {
  // дата сообщения
  const date = new Date(value);
  // сегодняшняя дата
  const today = new Date();
  // вчера: копия сегодняшней даты минус один день (setDate меняет день месяца)
  const yesterday = new Date();
  // вычитаем день
  yesterday.setDate(today.getDate() - 1);
  // toDateString — дата без времени, удобно сравнивать дни
  if (date.toDateString() === today.toDateString()) return 'Сегодня';
  // вчера
  if (date.toDateString() === yesterday.toDateString()) return 'Вчера';
  // иначе число и месяц словом
  return new Intl.DateTimeFormat('ru-RU', { day: 'numeric', month: 'long' }).format(date);
// конец функции formatDay
}

// ----------------------------------------------------------------------------
// pluralRu — правильное окончание слова после числа по правилам русского языка:
// 1 очко, 2 очка, 5 очков, 11 очков, 21 очко.
// Принимает: n — число; forms — три формы слова [для 1, для 2–4, для 5–20].
// Возвращает: нужную форму.
// ----------------------------------------------------------------------------
// export function
export function pluralRu(n, forms) {
  // % — остаток от деления: последние две цифры числа
  const lastTwo = Math.abs(n) % 100;
  // последняя цифра
  const last = lastTwo % 10;
  // 11–14 — всегда третья форма («11 очков»)
  if (lastTwo >= 11 && lastTwo <= 14) return forms[2];
  // оканчивается на 1 — первая форма («21 очко»)
  if (last === 1) return forms[0];
  // оканчивается на 2, 3, 4 — вторая форма («23 очка»)
  if (last >= 2 && last <= 4) return forms[1];
  // всё остальное — третья форма («25 очков»)
  return forms[2];
// конец функции pluralRu
}

// ----------------------------------------------------------------------------
// formatRelative — «только что», «5 мин назад», «3 ч назад» или дата.
// Принимает: value — дата. Возвращает: строку.
// ----------------------------------------------------------------------------
// export function
export function formatRelative(value) {
  // сколько секунд прошло: (сейчас − дата) / 1000; Math.max(0, ...) — не меньше нуля
  const seconds = Math.max(0, Math.round((Date.now() - new Date(value).getTime()) / 1000));
  // меньше минуты
  if (seconds < 60) return 'только что';
  // Math.floor — округление вниз; меньше часа — в минутах
  if (seconds < 3600) return `${Math.floor(seconds / 60)} мин назад`;
  // меньше суток — в часах
  if (seconds < 86400) return `${Math.floor(seconds / 3600)} ч назад`;
  // иначе обычная дата и время
  return formatDateTime(value);
// конец функции formatRelative
}
