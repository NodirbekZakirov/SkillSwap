// ============================================================================
// Файл: js/moderation.js
// Зачем нужен: поиск грубых слов в вопросах и ответах.
//   • findBadWords — какие грубые слова есть в тексте (сайт не даст их
//     опубликовать);
//   • highlightBadWords — безопасный HTML, где грубые слова выделены
//     тегом <mark> (так их видит администратор в панели модерации).
// Только чистые функции — их проверяет тест tests/moderation.test.mjs.
// Как связан с остальными: список слов — BAD_WORDS в js/config.js;
// используется в js/pages/questions.js, question.js и admin.js.
// ============================================================================

// список грубых слов
import { BAD_WORDS } from './config.js';

// BAD_SET — множество грубых слов (быстрая проверка has); ё заменяем на е, чтобы «ё» не помогало обойти фильтр
const BAD_SET = new Set(BAD_WORDS.map((word) => normalize(word)));

// ----------------------------------------------------------------------------
// normalize — приводит слово к единому виду: маленькие буквы, ё → е.
// Принимает: word. Возвращает: строку.
// ----------------------------------------------------------------------------
// function (объявления функций «поднимаются» наверх файла, поэтому её можно вызвать выше)
function normalize(word) {
  // toLowerCase — маленькие буквы; replace(/ё/g, 'е') — все «ё» в «е»
  return word.toLowerCase().replace(/ё/g, 'е');
// конец функции normalize
}

// ----------------------------------------------------------------------------
// findBadWords — ищет грубые слова в тексте.
// Принимает: text — текст. Возвращает: массив найденных слов без повторов
//   (пустой массив — всё хорошо).
// ----------------------------------------------------------------------------
// export function
export function findBadWords(text) {
  // split(/[^\p{L}]+/u) — делим текст на слова по всему, что НЕ буква (\p{L} — любая буква любого алфавита)
  const words = String(text ?? '').split(/[^\p{L}]+/u).map(normalize);
  // оставляем грубые; new Set убирает повторы; [...] превращает обратно в массив
  return [...new Set(words.filter((word) => BAD_SET.has(word)))];
// конец функции findBadWords
}

// ----------------------------------------------------------------------------
// highlightBadWords — безопасный HTML текста с подсветкой грубых слов.
// Каждый кусок текста экранируется, поэтому HTML-код из текста не выполнится.
// Принимает: text — текст; escape — функция экранирования (escapeHtml).
// Возвращает: строку HTML.
// ----------------------------------------------------------------------------
// export function
export function highlightBadWords(text, escape) {
  // split с круглыми скобками в шаблоне сохраняет разделители: получаем по очереди «не-буквы» и «слова»
  return String(text ?? '').split(/(\p{L}+)/u)
    // каждый кусок: грубое слово — в <mark>, остальное — просто экранируем
    .map((part) => (BAD_SET.has(normalize(part)) ? `<mark class="bad-word">${escape(part)}</mark>` : escape(part)))
    // склеиваем обратно
    .join('');
// конец функции highlightBadWords
}
