// ============================================================================
// Файл: js/auth.js
// Зачем нужен: всё про вход пользователя: получить текущую сессию, загрузить
// свой профиль, узнать «домашнюю» страницу по роли, выйти из аккаунта.
// Как связан с остальными: использует клиент из js/supabase.js. Его функции
// вызывают js/layout.js (проверка входа на каждой странице) и страницы входа
// и регистрации в js/pages/.
// ============================================================================

// подключение к Supabase
import { supabase } from './supabase.js';

// HOME_PAGES — объект-словарь: для каждой роли своя главная страница после входа
const HOME_PAGES = {
  // ученик попадает на экран совпадений
  student: '/pages/matches.html',
  // учитель — в панель учителя
  teacher: '/pages/teacher.html',
  // администратор — в панель администратора
  admin: '/pages/admin.html',
// конец объекта
};

// ----------------------------------------------------------------------------
// getSession — возвращает текущую сессию входа (или null, если не вошёл).
// Сессия хранится в браузере, supabase-js сам её обновляет.
// Принимает: ничего. Возвращает: Promise с объектом сессии или null.
// ----------------------------------------------------------------------------
// export async function — асинхронная функция, доступная другим модулям
export async function getSession() {
  // await ждёт ответа; { data, error } — деструктуризация: достаём два поля из объекта-ответа
  const { data, error } = await supabase.auth.getSession();
  // throw — «бросаем» ошибку дальше, её поймает try/catch того, кто вызвал функцию
  if (error) throw error;
  // data.session — сессия или null
  return data.session;
// конец функции getSession
}

// ----------------------------------------------------------------------------
// getMyProfile — загружает профиль пользователя вместе с названием школы.
// Принимает: userId — id пользователя.
// Возвращает: Promise с объектом профиля или null, если профиль не найден.
// ----------------------------------------------------------------------------
// export async function
export async function getMyProfile(userId) {
  // from('profiles') — таблица; select('*, schools(name)') — все столбцы профиля и название школы из связанной таблицы schools
  const { data, error } = await supabase
    // выбираем таблицу profiles
    .from('profiles')
    // * — все столбцы; schools(name) — поле name из связанной таблицы (связь по school_id)
    .select('*, schools(name)')
    // eq('id', userId) — условие «id равен userId» (eq — equal, «равно»)
    .eq('id', userId)
    // maybeSingle() — ждём одну строку или ни одной (тогда data будет null, а не ошибка)
    .maybeSingle();
  // при ошибке бросаем её дальше
  if (error) throw error;
  // возвращаем профиль
  return data;
// конец функции getMyProfile
}

// ----------------------------------------------------------------------------
// getHomePage — главная страница для роли.
// Принимает: role — 'student', 'teacher' или 'admin'. Возвращает: адрес страницы.
// ----------------------------------------------------------------------------
// export function
export function getHomePage(role) {
  // HOME_PAGES[role] — берём значение из словаря по ключу; если роли нет — страница профиля
  return HOME_PAGES[role] ?? '/pages/profile.html';
// конец функции getHomePage
}

// ----------------------------------------------------------------------------
// getSafeNextUrl — читает из адреса параметр ?next=..., куда вернуться после
// входа. Разрешаем только адреса НАШЕГО сайта (начинаются с одного «/»),
// иначе злоумышленник мог бы прислать ссылку, уводящую на чужой сайт.
// Принимает: ничего. Возвращает: адрес или null.
// ----------------------------------------------------------------------------
// export function
export function getSafeNextUrl() {
  // URLSearchParams разбирает часть адреса после «?»; location.search — эта часть, например «?next=%2Fpages%2Fchat.html»
  const next = new URLSearchParams(location.search).get('next');
  // startsWith — начинается ли строка с «/»; «//» запрещаем: так начинаются ссылки на другие сайты
  if (next && next.startsWith('/') && !next.startsWith('//')) return next;
  // иначе адреса нет
  return null;
// конец функции getSafeNextUrl
}

// ----------------------------------------------------------------------------
// formatName — имя для показа на сайте: «Амир Т.» (фамилия — только первая буква).
// Принимает: profile — объект с first_name и last_initial. Возвращает: строку.
// ----------------------------------------------------------------------------
// export function
export function formatName(profile) {
  // если буквы фамилии нет, показываем только имя
  return profile.last_initial ? `${profile.first_name} ${profile.last_initial}.` : profile.first_name;
// конец функции formatName
}

// ----------------------------------------------------------------------------
// signOut — выход из аккаунта и переход на главную страницу.
// Принимает: ничего. Возвращает: Promise.
// ----------------------------------------------------------------------------
// export async function
export async function signOut() {
  // try — выход может не получиться без интернета
  try {
    // signOut удаляет сессию из браузера и на сервере
    await supabase.auth.signOut();
  // catch — при ошибке сети всё равно забываем вход в этом браузере
  } catch (error) {
    // пишем предупреждение в консоль
    console.warn('Ошибка при выходе:', error);
    // забываем вход локально
    await clearLocalSession();
  // конец try/catch
  }
  // location.href = '/' — переход на главную страницу
  location.href = '/';
// конец функции signOut
}

// ----------------------------------------------------------------------------
// clearLocalSession — забывает вход в ЭТОМ браузере, не спрашивая сервер.
// Нужна, когда аккаунта уже нет (например, демо-данные создали заново):
// сервер такой вход не узнаёт, а браузер всё ещё «помнит» его.
// Принимает: ничего. Возвращает: Promise.
// ----------------------------------------------------------------------------
// export async function
export async function clearLocalSession() {
  // try — на всякий случай
  try {
    // scope: 'local' — удалить сессию только в этом браузере (запрос на сервер не нужен)
    await supabase.auth.signOut({ scope: 'local' });
  // catch — ошибка не страшна
  } catch (error) {
    // предупреждение в консоль
    console.warn('Ошибка при выходе:', error);
  // конец try/catch
  }
// конец функции clearLocalSession
}
